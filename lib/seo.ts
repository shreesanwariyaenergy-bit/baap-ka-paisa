import 'server-only';
// Search engine settings: who may index, the canonical address, and the pages offered to search engines.
// Metadata only; nothing here reads or writes data.
import type { Metadata } from 'next';
import { headers } from 'next/headers';
import { siteUrl } from './site';

/** The public address search engines should use. BKP_SITE_URL in production; the same domain everywhere else. */
export const CANONICAL_ORIGIN = 'https://baapkapaisa.com';
export const canonicalOrigin = (): string => siteUrl() ?? CANONICAL_ORIGIN;
export const SITE_NAME = 'BAAP KA PAISA';

/**
 * Search engines may index a page only when all three hold:
 *  - this is the production deployment (Vercel's VERCEL_ENV; previews and local development never qualify),
 *  - the request arrived on the canonical host (not baap-ka-paisa.vercel.app or a deployment address),
 *  - indexing has not been switched off with BKP_ALLOW_INDEXING=false (an emergency off switch).
 */
export async function indexingAllowed(): Promise<boolean> {
  if (process.env.VERCEL_ENV !== 'production') return false;
  if (process.env.BKP_ALLOW_INDEXING === 'false') return false;
  const host = (await headers()).get('host')?.toLowerCase().replace(/:\d+$/, '');
  return host === new URL(canonicalOrigin()).hostname;
}

/**
 * The pages offered to search engines (sitemap.xml). Only addresses that exist, answer 200 without a redirect and
 * carry their own content for any visitor. Not listed: query-string variants (city, locality and view boards are
 * empty templates until a season has members), account and sign-in pages, member pages and draft legal text.
 */
export const PUBLIC_PAGES = ['/', '/board', '/gazette', '/cities', '/india', '/throne', '/archive', '/seal', '/closing', '/simulator'] as const;

/** Kept out of search results, links still followed. */
export const NOINDEX: Metadata['robots'] = { index: false, follow: true };

/** The sharing image generated by app/opengraph-image.tsx (named here because a page's openGraph replaces the layout's). */
export const SHARE_IMAGE = { url: '/opengraph-image', width: 1200, height: 630, alt: 'BAAP KA PAISA — The Public Status Register. Who owns your city?' };

/**
 * Metadata for an indexable page: title, description, canonical address, Open Graph and X card. The robots value
 * is inherited from the root layout, which only allows indexing in production on the canonical host.
 */
export function pageMetadata({ title, description, path }: { title?: string; description: string; path: string }): Metadata {
  const ogTitle = title ? `${title} · ${SITE_NAME}` : `${SITE_NAME} — The Public Status Register`;
  return {
    ...(title ? { title } : {}),
    description,
    alternates: { canonical: path },
    openGraph: { type: 'website', siteName: SITE_NAME, locale: 'en_IN', url: path, title: ogTitle, description, images: [SHARE_IMAGE] },
    twitter: { card: 'summary_large_image', title: ogTitle, description, images: [SHARE_IMAGE.url] },
  };
}

/** Metadata for a page that stays out of search results (account, sign-in, member and draft pages, board variants). */
export function noindexMetadata(title: string): Metadata {
  return { title, robots: NOINDEX };
}
